// Короткие правила клуба: условия рассылки, правила акции с призами и условия участия.
// Это не договор, а описание того, как приложение работает на самом деле, — числа
// (заморозка золота, срок брони) берутся из тех же настроек, что и в коде.
// Без реквизитов оператора страницы не публикуются, как и политика ПДн.

import { esc, page, getPolicyOperator, missingPolicyVars } from './privacyPolicy.js';

function notReady(title) {
  return {
    status: 503,
    html: page(title, `<h1>${esc(title)}</h1><p>Документ готовится к публикации.</p>`),
  };
}

function operatorLine(op) {
  const req = [op.inn && `ИНН ${esc(op.inn)}`, op.ogrn && `ОГРН ${esc(op.ogrn)}`].filter(Boolean).join(', ');
  return `${esc(op.name)}${req ? ` (${req})` : ''}`;
}

const policyLink = '<a href="/legal/privacy-policy.html">Политике обработки персональных данных</a>';

export function renderMarketingConsent(env = process.env) {
  const title = 'Согласие на рекламные сообщения';
  if (missingPolicyVars(env).length) return notReady(title);
  const op = getPolicyOperator(env);
  const mail = `<a href="mailto:${esc(op.email)}">${esc(op.email)}</a>`;
  return {
    status: 200,
    html: page(title, `
<h1>${title}</h1>
<p class="muted">Приложение «Клуб Партнёров». Редакция от ${esc(op.editionDate)}.</p>
<p>Отмечая галочку при регистрации или включая переключатель в профиле, партнёр соглашается получать от ${operatorLine(op)} сообщения в Telegram или MAX: новости проектов, новые предложения и приглашения на мероприятия (ч. 1 ст. 18 Федерального закона «О рекламе»).</p>
<h2>Что важно</h2>
<ul>
  <li>Согласие добровольное. Без него приложением можно пользоваться полностью.</li>
  <li>Сообщения о собственной заявке, брони и сделке приходят всегда: это не реклама, а часть работы приложения.</li>
  <li>Отозвать согласие можно в любой момент переключателем в профиле или письмом на ${mail}. Рассылка прекращается сразу.</li>
  <li>Для рассылки используются только идентификатор в мессенджере и имя. Подробнее — в ${policyLink}.</li>
</ul>`),
  };
}

export function renderPrizeRules(env = process.env, { holdDays = 30 } = {}) {
  const title = 'Правила акции «Призы за сделки»';
  if (missingPolicyVars(env).length) return notReady(title);
  const op = getPolicyOperator(env);
  const mail = `<a href="mailto:${esc(op.email)}">${esc(op.email)}</a>`;
  const hold = holdDays > 0
    ? `<li>Монета становится доступной для обмена через ${holdDays} дней после подтверждения сделки. Это время нужно, чтобы убедиться, что сделка не расторгнута.</li>`
    : '';
  return {
    status: 200,
    html: page(title, `
<h1>${title}</h1>
<p class="muted">Приложение «Клуб Партнёров». Редакция от ${esc(op.editionDate)}.</p>
<p>Организатор акции — ${operatorLine(op)}. Участвуют партнёры, чья заявка в клуб одобрена.</p>

<h2>1. Как начисляется золото</h2>
<ul>
  <li>Золотая монета начисляется только за сделку, которая забронирована через приложение и закрыта отделом продаж как успешная.</li>
  <li>Сделка засчитывается, если покупатель не обращался в отдел продаж до брони в приложении.</li>
  <li>Дополнительное золото даёт миссия «Покоритель всех ЖК» — за сделки в разных жилых комплексах.</li>
  ${hold}
  <li>Серебро начисляется за активность в приложении и обменивается только на призы за серебро.</li>
</ul>

<h2>2. Как получить приз</h2>
<ul>
  <li>Партнёр оформляет заявку на приз в разделе «Маркет». Монеты списываются в момент заявки.</li>
  <li>Количество призов ограничено и указано на карточке. Приз получает тот, кто первым оформил заявку.</li>
  <li>Один партнёр может получить каждый приз за золото только один раз.</li>
  <li>Организатор проверяет заявку и связывается с партнёром для выдачи приза. Если заявку отклонили, монеты возвращаются, а приз снова становится доступен.</li>
  <li>Призы на денежный эквивалент не обмениваются.</li>
</ul>

<h2>3. Когда золото снимается</h2>
<ul>
  <li>Если сделка расторгнута или засчитана по ошибке, монета за неё и связанная награда за миссию снимаются.</li>
  <li>Золото, начисленное в обход правил, аннулируется, а заявки на призы с его использованием отклоняются.</li>
</ul>

<h2>4. Прочее</h2>
<ul>
  <li>Получение приза может повлечь обязанность уплатить налог на доход физических лиц в соответствии с Налоговым кодексом РФ. Порядок организатор сообщает при выдаче приза.</li>
  <li>Организатор может изменить правила или завершить акцию. Заявки, оформленные до изменения, выполняются по прежним правилам.</li>
  <li>Вопросы по акции: ${mail}.</li>
</ul>`),
  };
}

export function renderClubTerms(env = process.env, { bookingHoldHours = 72 } = {}) {
  const title = 'Условия участия в клубе';
  if (missingPolicyVars(env).length) return notReady(title);
  const op = getPolicyOperator(env);
  const mail = `<a href="mailto:${esc(op.email)}">${esc(op.email)}</a>`;
  const holdText = bookingHoldHours % 24 === 0
    ? `${bookingHoldHours / 24} ${bookingHoldHours / 24 === 1 ? 'сутки' : 'суток'}`
    : `${bookingHoldHours} ч`;
  return {
    status: 200,
    html: page(title, `
<h1>${title}</h1>
<p class="muted">Приложение «Клуб Партнёров». Редакция от ${esc(op.editionDate)}.</p>
<p>«Клуб Партнёров» — приложение ${operatorLine(op)} для риелторов и агентств, которые продают квартиры в проектах застройщика.</p>

<h2>1. Доступ</h2>
<ul>
  <li>Пользоваться клубом может риелтор или агентство, чью заявку одобрил организатор.</li>
  <li>Организатор может отклонить заявку или закрыть доступ, если партнёр нарушает эти условия или правила акции.</li>
  <li>Аккаунт личный. Партнёр отвечает за действия, совершённые под его входом.</li>
</ul>

<h2>2. Бронь в приложении</h2>
<ul>
  <li>Бронь в приложении — способ быстро сообщить отделу продаж о клиенте и придержать квартиру. Она фиксирует время и автора и попадает в CRM отдела продаж.</li>
  <li>Бронь в приложении действует ${holdText}, после чего квартира снова становится свободной. Окончательные условия покупки определяются договором с покупателем.</li>
  <li>Партнёр бронирует квартиру только для реального клиента и с его ведома. Данные и документы покупателя передаются только после его собственного согласия по ссылке.</li>
</ul>

<h2>3. Закрепление клиента</h2>
<ul>
  <li>Клиент считается приведённым партнёром, если бронь оформлена в приложении раньше, чем клиент сам обратился в отдел продаж.</li>
  <li>Спорные случаи разбирает отдел продаж по данным CRM и журналу приложения.</li>
</ul>

<h2>4. Рейтинг</h2>
<ul>
  <li>В рейтинге клуба все подтверждённые партнёры видят имя, фамилию и агентство участников и число их сделок. Так каждый видит, что соревнуется с реальными коллегами.</li>
  <li>Сделки в рейтинге — только подтверждённые отделом продаж.</li>
</ul>

<h2>5. Информация в приложении</h2>
<ul>
  <li>Цены, наличие и планировки обновляются из данных застройщика, но могут отличаться от актуальных. Перед сделкой их подтверждает отдел продаж.</li>
  <li>Материалы для клиентов (карточки квартир) содержат пометку «Реклама» и используются только для продажи квартир застройщика.</li>
</ul>

<h2>6. Прочее</h2>
<ul>
  <li>Призы и бонусы — по <a href="/legal/prize-rules.html">правилам акции</a>. Персональные данные — по ${policyLink}.</li>
  <li>Организатор может обновлять условия; действующая редакция всегда на этой странице.</li>
  <li>Вопросы: ${mail}.</li>
</ul>`),
  };
}
