// Политика обработки персональных данных (ч. 2 ст. 18.1 152-ФЗ требует её опубликовать).
// Текст описывает то, что приложение делает на самом деле: какие поля лежат в БД,
// куда уходят данные покупателя и что паспорт не хранится. Меняется код — сверяйте текст.
//
// Реквизиты оператора приходят из переменных окружения. Пока обязательные не заданы,
// вместо политики отдаётся честная заглушка: документ без названия оператора
// и контакта для обращений хуже, чем его отсутствие, — он вводит в заблуждение.

const REQUIRED = ['PD_OPERATOR_NAME', 'PD_OPERATOR_ADDRESS', 'PD_CONTACT_EMAIL'];

export const esc = (v) => String(v ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

export function getPolicyOperator(env = process.env) {
  return {
    name: env.PD_OPERATOR_NAME || '',
    inn: env.PD_OPERATOR_INN || '',
    ogrn: env.PD_OPERATOR_OGRN || '',
    address: env.PD_OPERATOR_ADDRESS || '',
    email: env.PD_CONTACT_EMAIL || '',
    phone: env.PD_CONTACT_PHONE || '',
    editionDate: env.PD_POLICY_DATE || '28.10.2026',
  };
}

export function missingPolicyVars(env = process.env) {
  return REQUIRED.filter((k) => !env[k]);
}

